"""
This module provides a client for interacting with a Large Language Model (LLM) via the OpenRouter API.
The LLMClient class encapsulates the functionality to send prompts to the LLM and receive structured
responses based on a specified JSON schema. The client uses the OpenAI SDK to communicate with the OpenRouter API.
The API key for authentication is expected to be set in the environment variable OPENROUTER_KEY.
"""

from openai import OpenAI
from pydantic import ValidationError
from config import config


class LLMClient:
	""" A client for interacting with a Large Language Model (LLM) via the OpenRouter API. 
	This class provides methods to generate responses from the LLM based on prompts. The API key for authentication is expected to
	be set in the environment variable OPENROUTER_KEY. The default model used for generating responses can be specified in the configuration.	

	Attributes:
		api_key (str): The API key for authenticating with the OpenRouter API.
		model_name (str): The name of the LLM model to use for generating responses.
		client (OpenAI): An instance of the OpenAI SDK client for communicating with the OpenRouter API.
	"""

	def __init__(self):
		""" Initialize the LLMClient with the API key and model name.
		The API key is retrieved from the environment variable OPENROUTER_KEY.
		The default model is specified in the configuration.
		"""
		self.api_key = config.OPENROUTER_KEY
		
		self.model_name = config.genai_model_name

		# Initialize the OpenAI SDK client pointing to OpenRouter's endpoint
		self.client = OpenAI(
            base_url="https://openrouter.ai/api/v1",
            api_key=self.api_key,
        )

	def generate_response(self, instruction: str,prompt: str, response_format: dict, top_k: int)-> dict:
		""" Generate a structured response from the LLM based on the provided prompt and JSON schema.

		Args:
			instruction (str): The system instruction to guide the LLM's behavior.
            prompt (str): The user prompt to send to the LLM for generating a response.
            response_format (dict): The JSON schema definition dictionary for the structured output.
			top_k (int): The expected number of items in the response, used for validation.

        Returns:
            dict: The parsed response generated by the LLM

		Raises:
			ValueError: If the LLM fails to parse the output, if the number of items in the response does not match top_k,
			or if any other error occurs during the request.
		"""
		try:
			response = self.client.chat.completions.parse(
				model = self.model_name,
				messages=[
					{"role": "system", "content": instruction},
					{"role": "user", "content": prompt},
				],
				response_format = response_format
			)

			parsed = response.choices[0].message.parsed
			# Handle cases where parsing failed or the model refused the response
			if parsed is None:
				refusal = response.choices[0].message.refusal
				raise ValueError(f"[-] Model failed to parse output. Refusal: {refusal}")

			# Validate the expected list length
			explanations = getattr(parsed, "explanations", [])
			if len(explanations) != top_k:
				raise ValueError(f"[-] Expected {top_k} items, but got {len(explanations)}. Please retry.")

			return parsed
		
		except ValidationError as ve:
			raise ValueError(f"[-] Validation error: {ve}") from ve
	
		except Exception as e:
			raise ValueError(f"[-] LLM request failed: {e}") from e

# Instantiate a global LLMClient for use in the application
llm_client = LLMClient()