""" Service for handling GenAI generation requests """

from genai import *
import json
from datetime import date
from genai.summaries import render_persona_narratives
from services.prioritization_service import ranking_sbom

def generate_explanations(sbom_id: int, top_k: int, baseline: bool = False, snapshot_date: date = None) -> dict | None:
    """
    Generate explanations for the top_k findings in a given SBOM ID.
    
    Args:
        sbom_id (int): The database ID of the ingested SBOM.
        top_k (int): The number of top findings to generate explanations for.
        baseline (bool): Whether to use the baseline prompt.
        snapshot_date (date): The date for which to generate explanations.
    Returns:
        dict | None: The parsed response generated by the LLM, or None if the request failed.
    """
    findings = ranking_sbom(sbom_id=sbom_id, snapshot_date=snapshot_date, fusion_ranking=True)["fusion"][:top_k]
    results = build_context_list(sbom_id, findings, snapshot_date=snapshot_date)

    if baseline:
        instruction = BASELINE_PROMPT.format(top_k=top_k)
        path = f"results/genai/baseline_explanations_{sbom_id}_{top_k}_{snapshot_date}.json"
    else:
        instruction = CONSTRAINED_PROMPT.format(top_k=top_k)
        path = f"results/genai/grounded_explanations_{sbom_id}_{top_k}_{snapshot_date}.json"

    answer = llm_client.generate_response(instruction=instruction, prompt=json.dumps(results), response_format=GroundedExplanationList, top_k=top_k)

    if answer:
        with open(path, "w") as outfile:
            outfile.write(answer.model_dump_json(indent=2))
        return answer

    return None

def generate_persona_narratives(sbom_id: int, top_k: int, snapshot_date: date, persona: str = "developer") -> dict:
    """
    Generate persona narratives for a list of grounded explanations.

    Args:
        sbom_id (int): The database ID of the ingested SBOM.
        top_k (int): The number of top findings to generate explanations for.
        snapshot_date (date): The date for which to generate explanations.
        persona (str): The persona for which to generate narratives. Defaults to "developer".
    Returns:
        list[dict]: A list of dictionaries containing the rendered narratives for each explanation. 
    """

    file_path = f"results/genai/grounded_explanations_{sbom_id}_{top_k}_{snapshot_date}.json"
    try:
        with open(file_path, "r") as infile:
            explanations_data = json.load(infile)
    except FileNotFoundError:
        raise FileNotFoundError(f"Grounded explanations file not found for SBOM ID {sbom_id} and date {snapshot_date}. Please run the 'generate_explanations' function first.")
    
    answer = GroundedExplanationList.model_validate(explanations_data)
    rendered_narratives = render_persona_narratives(answer, persona=persona)

    return answer, rendered_narratives