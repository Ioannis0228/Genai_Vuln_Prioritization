""" Service for handling GenAI generation requests """

from genai import *
import json

def generate_explanations(sbom_id: int, top_k: int, baseline: bool = False) -> dict | None:
    """
    Generate explanations for the top_k findings in a given SBOM ID.
    
    Args:
        sbom_id (int): The database ID of the ingested SBOM.
        top_k (int): The number of top findings to generate explanations for.
        baseline (bool): Whether to use the baseline prompt.

    Returns:
        dict | None: The parsed response generated by the LLM, or None if the request failed.
    """
    results = build_context_list(sbom_id=sbom_id, top_k=top_k)

    if baseline:
        instruction = BASELINE_PROMPT.format(top_k=top_k)
        path = f"results/genai/baseline_explanations_{sbom_id}_{top_k}.json"
    else:
        instruction = CONSTRAINED_PROMPT.format(top_k=top_k)
        path = f"results/genai/grounded_explanations_{sbom_id}_{top_k}.json"

    answer = llm_client.generate_response(instruction=instruction, prompt=json.dumps(results), response_format=GroundedExplanationList, top_k=top_k)
    
    if answer:
        with open(path, "w") as outfile:
            outfile.write(answer.model_dump_json(indent=2))
        return answer

    return None